create table if not exists public.ktx_meal_menus (
 id bigint generated by default as identity primary key,
 meal_date date not null,
 meal_period text not null check(meal_period in ('sang','trua','chieu')),
 vendor text not null check(length(trim(vendor)) between 1 and 160),
 menu_type text not null check(menu_type in ('man','chay')),
 dishes jsonb not null default '[]'::jsonb check(jsonb_typeof(dishes)='array'),
 updated_at timestamptz not null default now(),
 updated_by uuid references auth.users(id),
 unique(meal_date,meal_period,vendor,menu_type)
);
create index if not exists ktx_meal_menus_date_idx on public.ktx_meal_menus(meal_date,meal_period);
alter table public.ktx_meal_menus enable row level security;
drop policy if exists meal_monitor_read on public.ktx_meal_menus;
create policy meal_monitor_read on public.ktx_meal_menus for select to authenticated
 using(exists(select 1 from public.app_accounts a where a.user_id=(select auth.uid()) and a.enabled=true));
drop policy if exists meal_monitor_insert on public.ktx_meal_menus;
create policy meal_monitor_insert on public.ktx_meal_menus for insert to authenticated
 with check(exists(select 1 from public.app_accounts a where a.user_id=(select auth.uid()) and a.enabled=true and a.role in ('admin','manager')) and updated_by=(select auth.uid()));
drop policy if exists meal_monitor_update on public.ktx_meal_menus;
create policy meal_monitor_update on public.ktx_meal_menus for update to authenticated
 using(exists(select 1 from public.app_accounts a where a.user_id=(select auth.uid()) and a.enabled=true and a.role in ('admin','manager')))
 with check(exists(select 1 from public.app_accounts a where a.user_id=(select auth.uid()) and a.enabled=true and a.role in ('admin','manager')) and updated_by=(select auth.uid()));
revoke all on public.ktx_meal_menus from anon;
grant select,insert,update on public.ktx_meal_menus to authenticated;
grant usage,select on sequence public.ktx_meal_menus_id_seq to authenticated;
